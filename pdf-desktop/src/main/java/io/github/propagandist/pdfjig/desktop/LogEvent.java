package io.github.propagandist.pdfjig.desktop;

/**
 * ログに出す事象。
 *
 * <p><b>★ ログの口が受け取れるのはこの列挙だけである</b>（{@link Logs}）。自由な文字列を
 * 受け取る口を作らないのは、<b>そこがパスとファイル名の入口になるから</b>である——
 * {@code docs/SPEC.md} §10.4 が「書かない」と決めたものは、機械で守られていなければ
 * いつか書かれる（CLAUDE.md INV-5 が {@code String} のパスワードを禁じているのと同じ形）。
 *
 * <p>足すときは <b>{@code docs/SPEC.md} §10.4 の表を先に見ること</b>。
 * 事象の名前そのものが文書の特定につながらないかを、足す側が確かめる。
 */
enum LogEvent {

    /** 設定ファイルが読めない・壊れているので捨てた。 */
    SETTINGS_UNREADABLE("設定を読めなかったので既定に戻した"),

    /** 設定ファイルの値 1 つがパスとして読めない。 */
    SETTINGS_VALUE_UNREADABLE("設定の値をパスとして読めなかった"),

    /** 設定ファイルを書けなかった。覚えたフォルダは次の起動に残らない。 */
    SETTINGS_UNWRITABLE("設定を書けなかった"),

    /** 書き出しの作業場所を片づけられなかった。出力先に {@code .pdfjig-*} が残る。 */
    WORKSPACE_NOT_DISCARDED("書き出しの作業場所を片づけられなかった"),

    /**
     * 置き換える前の実体を、控えとして作業場所に残した。
     *
     * <p><b>★★ 出どころは 1 つだけである</b>——{@code DocumentWriter#restore}、つまり
     * <b>退避したあと入れ替えにも巻き戻しにも失敗したとき</b>である（#119）。
     * <b>そのとき出力先には何も無く、元のファイルは作業場所の中にしか無い。</b>
     *
     * <p><b>★ 「残した」ことそのものは書かない。</b>残すのは正しい振る舞いであって
     * 失敗ではなく、ログに書くのは失敗したことだけである（{@code docs/SPEC.md} §10.4）。
     * <b>ここが記録しているのは、その手前で起きた失敗のほうである</b>——
     * 2 か所から出すと、<b>1 回の保存で 2 行出るうえに「分からなかった」と
     * 「元がそこにしか無い」が同じ顔で並ぶ。</b>
     *
     * <p><b>どこに残したかは書かない。</b>フォルダ名もファイル名も文書の特定につながる
     * （{@code docs/SPEC.md} §10.4）。<b>ここが答えるのは「消していない」までである</b>——
     * 場所は、利用者が保存しようとしたフォルダの中にある。
     */
    REPLACED_FILE_KEPT("置き換える前のファイルを控えとして残した"),

    /** 画面に失敗として出した操作。何が起きたかは利用者にも見えている。 */
    OPERATION_FAILED("操作が失敗した"),

    /**
     * 更新を確認できなかった。遮断・DNS 不達・証明書・応答の形違いをまとめて指す。
     *
     * <p>画面には「確認できませんでした」の 1 行しか出ない（#72）。<b>押しても何も起きない、
     * という報告を受けたときに読む側の手がかりがここにしか無い。</b>
     */
    UPDATE_NOT_CHECKED("更新を確認できなかった"),

    /** どこも捕まえなかった例外。ここに出るものは想定していない経路である。 */
    UNCAUGHT("捕まえられなかった例外");

    private final String description;

    LogEvent(String description) {
        this.description = description;
    }

    /** 人が読むための説明。 */
    String description() {
        return description;
    }
}
