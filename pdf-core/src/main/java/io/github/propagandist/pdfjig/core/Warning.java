package io.github.propagandist.pdfjig.core;

/**
 * 操作は成功したが、利用者が知らなければ誤解する事柄。
 *
 * <p>{@link ErrorCode} と同じく <b>メッセージは定数であり、実行時の値を埋め込まない</b>
 * （CLAUDE.md INV-5）。
 */
public enum Warning {

    /**
     * 暗号化された入力を扱ったが、出力には保護が引き継がれない。
     *
     * <p>これを黙って行うと、利用者は保護されているつもりで平文の機密文書を配布することになる。
     */
    ENCRYPTION_NOT_PROPAGATED("入力の暗号化は出力に引き継がれません。出力されたファイルは保護されていません。"),

    /**
     * 保護を掛けたが、ユーザーパスワードが空なので出力は誰でも開ける。
     *
     * <p><b>★★ 「保護されていません」とは言えない。</b>出力には暗号化辞書もオーナーパスワードも
     * 権限フラグも載っており、{@link #ENCRYPTION_NOT_PROPAGATED} の文言はここでは嘘になる
     * ——<b>嘘を言えば、次に本当のときに読まれなくなる</b>（{@code CLAUDE.md} 優先順位 2）。
     *
     * <p><b>★ 告げるのは「誰でも開ける」ことである</b>（{@code docs/SPEC.md} §6.1）。
     * 残る権限フラグは<b>閲覧ソフトが自主的に従っているだけの申告制</b>であり、
     * <b>利用者はほぼ確実に「コピー禁止にしたから安全」と誤解する。</b>
     */
    CONTENT_OPENS_WITHOUT_A_KEY("ユーザーパスワードが空のため、出力されたファイルは誰でも開けます。権限の制限は閲覧ソフトの自主的な遵守に依存します。"),

    /**
     * 出力に含まれないページを指すしおりやリンクがあったため、それらを取り除いた。
     *
     * <p>取り除かないと、出力に含めなかったページが参照から辿れてしまい、
     * ページ一覧には出ないのにファイルの中には在る、という状態になる。
     * 押しても何も起きないしおりを残さないためでもある。
     */
    DANGLING_REFERENCES_REMOVED("出力に含まれないページを指すしおりとリンクを取り除きました。"),

    /**
     * 複数の入力を組み合わせたため、文書情報は最初の入力のものだけが残る。
     *
     * <p>題名や作成者を 1 つに決める根拠がない。黙って先頭のものを採ると、
     * 出力の題名が中身と食い違ったまま気づかれない。
     */
    METADATA_FROM_FIRST_INPUT("複数の入力を組み合わせたため、文書情報は最初の入力のものになります。"),

    /**
     * 電子署名のある入力を扱ったが、出力では署名が無効になる。
     *
     * <p>ページの並びを変えれば署名は必ず壊れる。追記でしか保てないものであり、
     * 保つ手立てはない。黙って壊すと、利用者は署名済みのつもりで検証に落ちる文書を配る。
     */
    SIGNATURE_INVALIDATED("入力には電子署名があります。出力されたファイルでは署名が無効になります。"),

    /**
     * 書き出したものが、ディスクへ届いたか確かめられなかった（#219）。
     *
     * <p><b>★★ 失敗にしない理由</b>——吐き出しを受け付けない場所（転送ドライブ・仮想マシンの共有フォルダなど）で
     * 失敗にすると、以前は通った書き出しが必ず失敗する。<b>ただし「本当に書けていなかった」も
     * ここに来る</b>（容量不足の共有フォルダ・傷んだディスク）——JDK の例外からは見分けられない。
     * <b>だから黙らずに伝える。</b>元のファイルを置き換える呼ぶ側は、これを見て置き換えを止めること
     * （{@link ErrorCode#OUTPUT_NOT_DURABLE}）。
     */
    NOT_DURABLE("書き出したファイルがディスクへ届いたか確かめられませんでした。保存先の不具合や容量不足で中身が欠けているおそれがあります。開いて確かめてください。");

    private final String defaultMessage;

    Warning(String defaultMessage) {
        this.defaultMessage = defaultMessage;
    }

    /**
     * 利用者に提示してよい定型メッセージを返す。
     *
     * @return 実行時の値を含まない定数メッセージ
     */
    public String defaultMessage() {
        return defaultMessage;
    }
}
