package io.github.propagandist.pdfjig.core;

/**
 * pdfjig が投げる失敗の分類。
 *
 * <p>ここに定義するメッセージは <b>定数であり、実行時の値を一切埋め込まない</b>。
 * パスワード・ファイルパス・文書の中身が例外メッセージ経由で
 * ログに流出することを構造的に防ぐため（CLAUDE.md INV-5）。
 */
public enum ErrorCode {

    /** 入力ファイルが存在しない、またはファイルではない（フォルダなど）。 */
    FILE_NOT_FOUND("入力ファイルを開けません。"),

    /**
     * 入力ファイルは在るが、いま読み取れない（#147）。
     *
     * <p><b>Windows では、ほかのアプリやウイルス対策ソフトが開いているだけで起きる。</b>
     * {@link #NOT_A_PDF} を返すと「さっきまで開けていた PDF が壊れた」と読ませる（優先順位 2）。
     */
    FILE_UNREADABLE("ファイルを読み取れません。ほかのアプリで開いていれば、閉じてからやり直してください。"),

    /** 入力が 1 つも指定されていない。 */
    NO_INPUT("入力が指定されていません。"),

    /** PDF として解釈できない。 */
    NOT_A_PDF("PDF として読み取れません。"),

    /** 暗号化されており、パスワードが必要。 */
    PASSWORD_REQUIRED("この文書はパスワードで保護されています。"),

    /** パスワードが誤っている。 */
    INVALID_PASSWORD("パスワードが正しくありません。"),

    /**
     * パスワード付きで開こうとして失敗したが、パスワードと文書のどちらが原因かを絞れない。
     *
     * <p><b>絞れないときにだけ使う。</b>原因が分かるならそちらの符号を当てること。
     * ここへ寄せると、利用者は次に何をすればよいかを 2 通り試すことになる。
     */
    PASSWORD_OR_DOCUMENT_FAILURE("パスワードか文書のどちらかに問題があり、開けませんでした。"),

    /** 指定されたページが文書の範囲外。 */
    PAGE_OUT_OF_RANGE("指定されたページが文書の範囲外です。"),

    /** ページ順の指定が全ページの並べ替えになっていない。 */
    INVALID_PAGE_ORDER("ページ順の指定が全ページの並べ替えになっていません。"),

    /** 操作の結果、ページが 1 枚も残らない。 */
    EMPTY_RESULT("この操作を行うとページが 1 枚も残りません。"),

    /**
     * 開いたファイルにページが 1 枚も無い（#148）。
     *
     * <p><b>{@link #EMPTY_RESULT} と分けてある。</b>あちらの文言は「この操作を行うと」であり、
     * 空の PDF を足したときに出すと、<b>開いているページを失う警告に読める</b>（優先順位 2）。
     */
    EMPTY_DOCUMENT("このファイルにはページがありません。"),

    /** 対応していない暗号化方式。 */
    UNSUPPORTED_ENCRYPTION("この暗号化方式には対応していません。"),

    /** 指定された暗号化の引き継ぎ方法に対応していない。 */
    ENCRYPTION_PROPAGATION_UNSUPPORTED("この暗号化の引き継ぎ方法には対応していません。"),

    /** テキストを抽出できない。 */
    TEXT_EXTRACTION_FAILED("テキストを抽出できませんでした。"),

    /** ページを画像に描画できない。 */
    RENDERING_FAILED("ページを表示用の画像に変換できませんでした。"),

    /** サムネイルの描画が止まらず、受け持っている文書を触れない。 */
    THUMBNAIL_RENDERING_BUSY("サムネイルの描画が終わらないため、この操作を行えません。"),

    /** 出力先に同名のファイルが既に存在する。 */
    OUTPUT_ALREADY_EXISTS("出力先に同名のファイルが既に存在します。"),

    /**
     * 書き出したものがディスクへ届いたか確かめられなかったので、元のファイルを置き換えなかった（#219）。
     *
     * <p><b>元は手つかずで残っている。</b>届く前に置き換えて控えを消すと、直後の電源断で新旧どちらも失いうる。
     * 何が起きうるかは {@link Warning#NOT_DURABLE} を見ること。
     */
    OUTPUT_NOT_DURABLE("書き出したファイルがディスクへ届いたか確かめられなかったため、元のファイルを置き換えませんでした。元のファイルはそのままです。"),

    /** 読み書きの失敗。 */
    IO_FAILURE("ファイルの読み書きに失敗しました。");

    private final String defaultMessage;

    ErrorCode(String defaultMessage) {
        this.defaultMessage = defaultMessage;
    }

    /**
     * 利用者に提示してよい定型メッセージを返す。
     *
     * @return 実行時の値を含まない定数メッセージ
     */
    public String defaultMessage() {
        return defaultMessage;
    }
}
